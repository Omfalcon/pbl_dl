"""Data Models and Pydantic Schemas for PhishVision AI Scanner."""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any
from pydantic import BaseModel, Field


class ScanStatus(str, Enum):
    """Execution status of a scan job."""
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    TIMED_OUT = "TIMED_OUT"
    BLOCKED_SSRF = "BLOCKED_SSRF"
    IN_PROGRESS = "IN_PROGRESS"


class RedirectHop(BaseModel):
    """Represents a single step in a navigation redirect chain."""
    step: int = Field(..., description="Chronological 1-based index in redirect sequence")
    url: str = Field(..., description="Target URL of the redirect step")
    status_code: int = Field(..., description="HTTP response status code (e.g. 301, 302, 200)")
    domain: str = Field(..., description="Registrable domain or hostname of this hop")
    headers: dict[str, str] = Field(default_factory=dict, description="Captured response headers")


class FormField(BaseModel):
    """Metadata for an individual input/button element inside an HTML form."""
    name: str = Field(default="", description="Name attribute of the input")
    field_id: str = Field(default="", description="ID attribute of the input")
    field_type: str = Field(default="text", description="Type attribute (e.g. text, password, email, submit)")
    placeholder: str = Field(default="", description="Input placeholder string")
    autocomplete: str = Field(default="", description="Autocomplete attribute value")
    is_password: bool = Field(default=False, description="Whether this field accepts passwords")
    is_required: bool = Field(default=False, description="Whether this field has required attribute")


class FormInfo(BaseModel):
    """Metadata describing an HTML form and its submission action."""
    form_id: str = Field(default="", description="DOM ID or generated index of the form")
    action_url: str = Field(default="", description="Form action attribute destination")
    action_domain: str = Field(default="", description="Registrable domain receiving the form payload")
    method: str = Field(default="GET", description="HTTP method (POST, GET)")
    is_external_submission: bool = Field(default=False, description="True if action destination points to a different domain")
    fields: list[FormField] = Field(default_factory=list, description="List of parsed input fields")
    has_password_field: bool = Field(default=False, description="True if form contains at least one password input")


class ScriptInfo(BaseModel):
    """Metadata for inline and externally hosted JavaScript elements."""
    src: str = Field(default="", description="Script source URL if external, empty if inline")
    domain: str = Field(default="", description="Origin domain of the script host")
    is_external: bool = Field(default=False, description="True if script is loaded from an external domain")
    is_inline: bool = Field(default=False, description="True if script body is embedded directly in HTML")
    async_attr: bool = Field(default=False, description="Whether async attribute was set")
    defer_attr: bool = Field(default=False, description="Whether defer attribute was set")


class ScanOptions(BaseModel):
    """Configuration options for Playwright scanner execution."""
    viewport_width: int = Field(default=1280, ge=320, le=3840)
    viewport_height: int = Field(default=720, ge=240, le=2160)
    timeout_seconds: int = Field(default=15, ge=3, le=60)
    capture_full_page: bool = Field(default=True)
    user_agent: str | None = Field(default=None)
    extract_scripts: bool = Field(default=True)
    extract_forms: bool = Field(default=True)


class ScanResult(BaseModel):
    """Structured forensic report generated by the Playwright secure scanner."""
    scan_id: str = Field(..., description="Unique UUIDv4 identifying this scan operation")
    requested_url: str = Field(..., description="Original raw URL requested by caller")
    final_url: str = Field(..., description="Final landing URL after all redirects")
    status: ScanStatus = Field(..., description="Final status of the scanner execution")
    status_code: int | None = Field(default=None, description="Final HTTP status code")
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc), description="UTC timestamp of scan initiation")
    page_title: str | None = Field(default=None, description="Rendered page title (<title>)")
    
    # Forensic Evidence Paths
    viewport_screenshot_path: str | None = Field(default=None, description="Path to captured viewport screenshot PNG")
    full_page_screenshot_path: str | None = Field(default=None, description="Path to full-page screenshot PNG")
    dom_snapshot_path: str | None = Field(default=None, description="Path to sanitized rendered HTML DOM snapshot")
    
    # Behavioral & Network Intelligence
    redirect_chain: list[RedirectHop] = Field(default_factory=list, description="Chronological chain of HTTP redirects")
    domain_transitions: list[str] = Field(default_factory=list, description="Unique domain hops during navigation")
    forms: list[FormInfo] = Field(default_factory=list, description="Parsed HTML forms and targets")
    scripts: list[ScriptInfo] = Field(default_factory=list, description="Discovered script references")
    meta_tags: dict[str, str] = Field(default_factory=dict, description="Extracted HTML meta tags")
    
    # Operational Telemetry
    scan_duration_ms: float = Field(default=0.0, description="Total execution duration in milliseconds")
    errors: list[str] = Field(default_factory=list, description="Errors encountered during scanning")
    warnings: list[str] = Field(default_factory=list, description="Warnings or non-fatal security flags")
    security_metadata: dict[str, Any] = Field(default_factory=dict, description="Resolved IP, pinned IP, and anti-SSRF verification details")
